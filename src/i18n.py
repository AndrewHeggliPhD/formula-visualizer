def t(key: str, lang: str = "no", **kwargs: object) -> str:
    """Translate a key into the active language with optional formatting."""
    table = TRANSLATIONS.get(lang, TRANSLATIONS["no"])
    text = table.get(key, TRANSLATIONS["no"].get(key, key))
    if kwargs:
        try:
            return text.format(**kwargs)
        except (KeyError, ValueError):
            return text
    return text
